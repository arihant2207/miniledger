/**
 * Module: Edge Validation Middleware
 * Responsibility: Enforces schema validation at the HTTP edge using Zod.
 * Parses and sanitizes request bodies, queries, and parameters before controllers execute,
 * ensuring malformed payloads never reach domain services.
 */

import { Request, Response, NextFunction } from 'express';
import { ZodSchema } from 'zod';

export function validateBody<T>(schema: ZodSchema<T>) {
  return (req: Request, _res: Response, next: NextFunction): void => {
    try {
      req.body = schema.parse(req.body);
      next();
    } catch (error) {
      next(error);
    }
  };
}

export function validateQuery<T>(schema: ZodSchema<T>) {
  return (req: Request, _res: Response, next: NextFunction): void => {
    try {
      req.query = schema.parse(req.query) as unknown as Request['query'];
      next();
    } catch (error) {
      next(error);
    }
  };
}

export function validateParams<T>(schema: ZodSchema<T>) {
  return (req: Request, _res: Response, next: NextFunction): void => {
    try {
      req.params = schema.parse(req.params) as unknown as Request['params'];
      next();
    } catch (error) {
      next(error);
    }
  };
}
